const getTranslation = (language, key) => translations[language]?.[key] ?? translations.es[key] ?? key;
const languageButtons = [...document.querySelectorAll('[data-language]')];

function applyLanguage(language, persist = true) {
  const nextLanguage = language === 'en' ? 'en' : 'es';
  document.documentElement.lang = nextLanguage;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = getTranslation(nextLanguage, element.dataset.i18n);
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    const [attribute, key] = element.dataset.i18nAttr.split('|');
    element.setAttribute(attribute, getTranslation(nextLanguage, key));
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === nextLanguage;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  if (persist) {
    try {
      window.localStorage.setItem('leyre-language', nextLanguage);
    } catch {
      // Local storage can be unavailable on some file:// contexts.
    }
  }
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.language));
});

